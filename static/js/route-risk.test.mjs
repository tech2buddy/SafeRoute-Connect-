import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('./route-risk.js',import.meta.url),'utf8');
const {assessRoute,rankRoutes,segmentDistance}=await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const now=Date.parse('2026-10-12T12:00:00Z');
const route={duration:600,geometry:{coordinates:[[24.75,-28.75],[24.76,-28.75]]}};
const report={id:'one',origin:'community',latitude:-28.75,longitude:24.755,severity:'risky',incident_type:'harassment',location:'Sample street',occurred_at:'2026-10-12T11:00:00Z'};
assert.equal(assessRoute(route,null,now).key,'unknown');
assert.equal(assessRoute(route,[],now).score,0);
assert.equal(assessRoute(route,[report],now).score,6);
assert.equal(assessRoute(route,[report],now).key,'risky');
assert.equal(assessRoute(route,[report,report],now).score,6);
assert.equal(assessRoute(route,[{...report,occurred_at:'2026-10-10T12:00:00Z'}],now).score,3.6);
for(const change of [{origin:'demo'},{origin:'search_candidate'},{is_demo:true},{status:'resolved'},{occurred_at:'2026-10-13T12:00:00Z'},{occurred_at:'2026-10-01T12:00:00Z'},{latitude:0},{origin:'imported',location_precision:'approximate',expires_at:'2026-10-13T12:00:00Z'},{origin:'imported',location_precision:'exact',expires_at:'2026-10-11T12:00:00Z'}]) assert.equal(assessRoute(route,[{...report,...change}],now).score,0);
assert.equal(assessRoute(route,[{...report,origin:'imported',location_precision:'exact',expires_at:'2026-10-13T12:00:00Z'}],now).score,6);
assert(segmentDistance([24.755,-28.75],[24.75,-28.75],[24.76,-28.75])<.01);
const alternative={duration:900,geometry:{coordinates:[[24.75,-28.76],[24.76,-28.76]]}};
assert.equal(rankRoutes([route,alternative],[report],'safest',now)[0].duration,900);
assert.equal(rankRoutes([route,alternative],[report],'fastest',now)[0].duration,600);
assert.equal(rankRoutes([route,alternative],[report],'balanced',now)[0].duration,900);
console.log('Route risk tests passed: exclusions, deduplication, scoring, geometry, and ranking.');
const hazard={...report,id:'scenario-risk',origin:'presentation',is_demo:true,feature_kind:'hazard'};
const support={...report,id:'scenario-support',origin:'presentation',is_demo:true,feature_kind:'support',severity:'safe',incident_type:'Maintained footpath'};
assert.equal(assessRoute(route,[hazard,support],now).score,0);
const result=assessRoute(route,[hazard,support],now,{presentation:true});
assert.equal(result.score,6);
assert.equal(result.key,'risky');
assert.equal(result.supports.length,1);
assert.equal(result.matches.length,1);
const safeSupport={...support,longitude:24.755,latitude:-28.76};
assert.equal(rankRoutes([route,alternative],[safeSupport],'safest',now,{presentation:true})[0].duration,900);
console.log('Presentation tests passed: opt-in isolation, positive features, and serious-risk preservation.');
